#!/usr/bin/env python3
"""Generates src/fsr1_shaders.h: embeds ffx_a.h + ffx_fsr1.h + fsr1_main.hlsl as one
string literal per source line (this MSVC's C2026 limit is ~16.4 KB per literal,
well below the documented 65,535). The proxy joins them with '\\n' at runtime."""
import io, json, os

HERE = os.path.dirname(os.path.abspath(__file__))

def read(name):
    with io.open(os.path.join(HERE, name), "r", encoding="utf-8") as f:
        return f.read()

ffx_a = read("ffx_a.h")
ffx_fsr1 = read("ffx_fsr1.h")
main = read("fsr1_main.hlsl")

all_text = "\n".join(["#define A_GPU 1", "#define A_HLSL 1", ffx_a,
                      "#define FSR_EASU_F 1", "#define FSR_RCAS_F 1", ffx_fsr1, "", main])
lines = all_text.split("\n")

hdr = "/* Generated by make_fsr1_header.py - DO NOT EDIT BY HAND.\n"
hdr += "   AMD FidelityFX Super Resolution 1 (MIT), see THIRD_PARTY_NOTICES in the repo. */\n"
hdr += "/* One string literal per source line: this MSVC's C2026 string limit (~16.4 KB\n"
hdr += "   despite the documented 65,535) rejects any bigger single literal. The proxy joins\n"
hdr += "   the lines with '\\n' at runtime. */\n"
hdr += "static const char* const g_fsr1Parts[] = {\n"
for ln in lines:
    esc = json.dumps(ln)  # C/C++ compatible escaping, ASCII-safe
    hdr += esc + ",\n"
hdr += "};\n"
hdr += "static const UINT g_fsr1PartCount = sizeof(g_fsr1Parts) / sizeof(g_fsr1Parts[0]);\n"

out_path = os.path.join(HERE, "fsr1_shaders.h")
with io.open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(hdr)
# Joined HLSL for offline fxc validation.
with io.open(os.path.join(HERE, "fsr1_joined_test.hlsl"), "w", encoding="utf-8", newline="\n") as f:
    f.write(all_text)
print("wrote", out_path, os.path.getsize(out_path), "bytes,", len(lines), "literals")
